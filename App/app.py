@st.cache_data
def construir_modelo_kmeans(ruta_csv: str, k_seleccionado: int = 5):
    """
    Carga el dataset Mall_Customers.csv, realiza la limpieza y estandarización
    de variables numéricas, evalúa K de 2 a 10 y entrena el modelo K-Means final.
    """
    # 2.1 Carga de datos directamente desde el archivo CSV
    df = pd.read_csv(ruta_csv)

    # 2.2 Selección de variables comerciales para el agrupamiento
    columnas_modelo = ['Annual Income (k$)', 'Spending Score (1-100)']
    X = df[columnas_modelo]

    # 2.3 Estandarización (Media = 0, Desviación Estándar = 1)
    # Indispensable en K-Means porque utiliza distancias euclidianas
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    # 2.4 Cálculo de métricas para Método del Codo y Silueta (k = 2 a 10)
    rango_k = list(range(2, 11))
    inercias = []
    siluetas = []
    for k in rango_k:
        km_temp = KMeans(n_clusters=k, init='k-means++', n_init=10, random_state=42)
        etiquetas_temp = km_temp.fit_predict(X_scaled)
        inercias.append(km_temp.inertia_)
        siluetas.append(silhouette_score(X_scaled, etiquetas_temp))

    # 2.5 Entrenamiento del modelo K-Means con el número de clústeres k_seleccionado
    kmeans = KMeans(n_clusters=k_seleccionado, init='k-means++', n_init=10, random_state=42)
    df['Cluster'] = kmeans.fit_predict(X_scaled)
    df['Silueta_Individual'] = silhouette_samples(X_scaled, df['Cluster'])

    # 2.6 Reconversión de los centroides a su escala original (miles de USD y puntos 1-100)
    centroides_orig = scaler.inverse_transform(kmeans.cluster_centers_)
    silueta_global = silhouette_score(X_scaled, df['Cluster'])
    inercia_actual = kmeans.inertia_

    return df, scaler, kmeans, centroides_orig, silueta_global, inercia_actual, rango_k, inercias, siluetas

